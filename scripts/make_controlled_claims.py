SYNTHETIC_OUTPUT_PATH = os.path.join(DATA_DIR, "validation_claims_synthetic.csv")
SYNTHETIC_KEY_PATH = os.path.join(DATA_DIR, "synthetic_key.csv")

# Casimir baseline topic to exclude
CASIMIR_TOPIC = "Perpetual mechanical energy extraction from Casimir cavity forces"

BOILERPLATE_PATTERNS = [
    "in this study", "we found", "this review", "here we", "figure", "table",
    "author", "doi:", "http", "copyright", "advertisement", "cells cells pdf",
    "article cas pubmed", "article pubmed", "to obtain the best experience",
    "you are using a browser", "in the meantime", "conferences >", "this is a preview",
    "subscribe to this journal", "buy this article", "prices may be", "access options",
    "google scholar", "download references"
]


class GeneratedClaimItem(BaseModel):
    id: int = Field(description="The numeric item id (1 through 6) matching the input")
    text: str = Field(description="The standalone rewritten claim")


class GeneratedClaimsList(BaseModel):
    claims: List[GeneratedClaimItem] = Field(description="List of 6 rewritten claims")


def clean_sentence_text(s: str) -> str:
    """Strip figure references, citations, LaTeX math, and leading bullets."""
    s = re.sub(r"\(Fig\.[^)]*\)", "", s)
    s = re.sub(r"\(Figs\.[^)]*\)", "", s)
    s = re.sub(r"\(see\s+Fig[^)]*\)", "", s, flags=re.I)
    s = re.sub(r"\(\*[\d,\s–-]+\*\)", "", s)
    s = re.sub(r"\[[\d,\s–-]+\]", "", s)
    s = re.sub(r"\\\[[\s\S]*?\\\]|\\\(.*?\\\)", "", s)
    s = re.sub(r"^\s*[-*•#>]+\s*", "", s)
    s = re.sub(r"^\s*(?:by\s+[A-Z]\s+[A-Za-z]+|\d+)\s*[·•]\s*\d{4}\s*[·•]\s*Cited by \d+\s*—\s*", "", s, flags=re.I)
    s = re.sub(r"^\s*\d+[A-Z]\)\s*", "", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def is_boilerplate(s: str) -> bool:
    low = s.lower()
    return any(bp in low for bp in BOILERPLATE_PATTERNS)


def extract_candidate_sentences(passages: List[str]) -> List[Tuple[int, str]]:
    """Extract clean, factual candidate sentences from evidence passages.
    
    Returns list of (passage_index, cleaned_sentence).
    """
    candidates: List[Tuple[int, str]] = []
    seen = set()

    for p_idx, p in enumerate(passages):
        cleaned_p = re.sub(r"(?:by\s+[A-Z]\s+[A-Za-z]+|\d+)\s*[·•]\s*\d{4}\s*[·•]\s*Cited by \d+\s*—\s*", ". ", p, flags=re.I)
        cleaned_p = re.sub(r"\(Fig\.\s*(\d+[A-Z]?)\)", r"(Figure \1)", cleaned_p)
        cleaned_p = re.sub(r"\(Figs\.\s*([^)]*)\)", r"(Figures \1)", cleaned_p)
        cleaned_p = re.sub(r"\s*###\s*", ". ", cleaned_p)
        cleaned_p = re.sub(r"\s*;\s*", ". ", cleaned_p)
        cleaned_p = re.sub(r"([a-z]{2,})\s+(The|This|These|However|Moreover|In\s+situ|In\s+another|Although|Consequently)\b", r"\1. \2", cleaned_p)

        prot = protect_abbreviations(cleaned_p)
        raw_sents = re.split(r"(?<=[.!?])\s+", prot)

        for raw_s in raw_sents:
            s = unprotect_abbreviations(raw_s)
            s = clean_sentence_text(s)
            if not s or is_boilerplate(s):
                continue

            words = s.split()
            sub_sents = [s]
            if len(words) > 40:
                parts = re.split(r",\s+(?=which|contributing|resulting|leading)\s*|\s*\((?:LiNi|CCD|with)\s*", s)
                if len(parts) > 1:
                    sub_sents = [clean_sentence_text(part) for part in parts if part.strip()]

            for cand in sub_sents:
                c_words = cand.split()
                if not (9 <= len(c_words) <= 45):
                    continue
                if is_boilerplate(cand):
                    continue

                has_num = bool(re.search(r"\d", cand))
                has_entity = any(w[0].isupper() for w in c_words[1:] if len(w) > 1 and w.isalpha())
                has_verb = bool(re.search(
                    r"\b(cell|protein|gene|dna|rna|reaction|phase|layer|energy|heat|force|pressure|temperature|"
                    r"surface|carbon|oxide|catalyst|electrolyte|metal|pore|calcium|silicon|hydrate|cement|clast|"
                    r"pruning|synap|dopamine|neuron|inlet|aerodynamic|trophic|plastic|pelagic|permafrost|thaw|methane|"
                    r"lake|vaccine|tumor|melanoma|perovskite|quantum|diamond|nitrogen|hydrothermal|vent|sulfur|crispr|"
                    r"cas9|inhibit|activate|reduce|increase|bind|cleave|catalyze|regulate|mediate|produce|synthesize|"
                    r"degrade|generate|stabilize|induce|suppress|promote|correlate|decrease|oxidize|absorb|transform|"
                    r"encode|mapping|mortar|durability)\b",
                    cand,
                    re.I,
                ))

                if (has_num or has_entity or has_verb) and cand not in seen:
                    seen.add(cand)
                    candidates.append((p_idx, cand))

    return candidates


def select_six_sentences(
    candidates: List[Tuple[int, str]],
    seed: int = 42,
) -> List[Tuple[int, str]]:
    """Select exactly 6 distinct source sentences, balancing across different passages where possible."""
    if len(candidates) < 6:
        raise ValueError(f"Fewer than 6 candidate sentences found ({len(candidates)}).")

    # Group by passage index
    passage_to_cands: Dict[int, List[str]] = {}
    for p_idx, s in candidates:
        passage_to_cands.setdefault(p_idx, []).append(s)

    rng = random.Random(seed)

    # Shuffle candidates within each passage
    for p_idx in passage_to_cands:
        rng.shuffle(passage_to_cands[p_idx])

    selected: List[Tuple[int, str]] = []
    p_indices = sorted(list(passage_to_cands.keys()))
    rng.shuffle(p_indices)

    # First pass: take at most 1 from each passage
    for p_idx in p_indices:
        if len(selected) >= 6:
            break
        if passage_to_cands[p_idx]:
            selected.append((p_idx, passage_to_cands[p_idx].pop(0)))

    # Second pass: fill remaining from passages with extra candidates
    if len(selected) < 6:
        remaining_pool = []
        for p_idx, cands in passage_to_cands.items():
            for c in cands:
                remaining_pool.append((p_idx, c))
        rng.shuffle(remaining_pool)
        for item in remaining_pool:
            if len(selected) >= 6:
                break
            selected.append(item)

    if len(selected) != 6:
        raise RuntimeError(f"Could not select exactly 6 sentences (got {len(selected)}).")

    return selected


def get_generator_prompt():
    """Build the ChatPromptTemplate for controlled claim generation."""
    system_msg = (
        "You are an expert scientific fact annotator. Your task is to rewrite individual source sentences "
        "into standalone factual claims following precise instructions for each sentence."
    )
    human_msg = """You are given 6 sentences from research evidence on the topic: "{topic}".
Rewrite each sentence into a standalone claim according to its specified task.

Rules:
- For FAITHFUL sentences: Paraphrase the sentence as a standalone claim. Keep every fact (numbers, names, relations). Do not add anything.
- For CORRUPTED sentences: Rewrite the sentence as a standalone claim with exactly ONE factual change (a number, an entity, a direction/negation, or a causal link). Keep wording and length similar.

Sentences:
{sentences_block}

Output a structured list of items (id 1 to 6) with their rewritten text."""

    return ChatPromptTemplate.from_messages([
        ("system", system_msg),
        ("human", human_msg),
    ])


def build_generator_chain(llm_instance=None):
    """Build the structured output generation chain."""
    active_llm = llm_instance or llm
    structured_llm = active_llm.with_structured_output(GeneratedClaimsList, method="json_schema")
    return get_generator_prompt() | structured_llm


def run_controlled_generation(
    seed: int = 42,
    llm_instance=None,
    dry_run: bool = False,
) -> Dict[str, Any]:
    """Execute controlled claim generation for all 12 target reports."""
    if not os.path.exists(LABELED_REPORTS_PATH):
        raise FileNotFoundError(f"Source file not found: {LABELED_REPORTS_PATH}")

    df_reports = pd.read_csv(LABELED_REPORTS_PATH)

    # 1. Identify 12 NEW-topic reports (excluding Casimir)
    unique_reports = df_reports[["report_id", "topic"]].drop_duplicates()
    target_reports = unique_reports[unique_reports["topic"] != CASIMIR_TOPIC].copy()

    if len(target_reports) != 12:
        raise ValueError(f"Expected 12 target reports, found {len(target_reports)}: {list(target_reports['report_id'])}")

    print(f"Targeting {len(target_reports)} reports (excluding Casimir baseline).")

    chain = build_generator_chain(llm_instance=llm_instance)

    synthetic_rows = []
    key_rows = []
    faithful_retrieval_misses = 0
    total_faithful = 0
    total_corrupted = 0

    # Sort report IDs for deterministic execution
    target_reports = target_reports.sort_values(by="report_id").reset_index(drop=True)

    for rep_idx, row in target_reports.iterrows():
        report_id = str(row["report_id"]).strip()
        topic = str(row["topic"]).strip()

        # Check token usage limit before call
        if TOKEN_USAGE["total_tokens"] >= TOKEN_LIMIT_PER_RUN:
            raise RuntimeError(
                f"TOKEN_LIMIT_PER_RUN ({TOKEN_LIMIT_PER_RUN}) exceeded! Total tokens: {TOKEN_USAGE['total_tokens']}"
            )

        # Locate results JSON
        match_files = glob.glob(os.path.join(RESULTS_DIR, f"{report_id}*.json"))
        if not match_files:
            raise FileNotFoundError(f"Results JSON not found for report {report_id} in {RESULTS_DIR}")
        with open(match_files[0], "r", encoding="utf-8") as f:
            res_data = json.load(f)

        raw_contexts = res_data.get("contexts", [])
        passages = clean_evidence_passages(raw_contexts)
        if not passages:
            raise ValueError(f"No cleaned passages found for report {report_id}")

        # Extract candidates and select 6
        cands = extract_candidate_sentences(passages)
        selected_6 = select_six_sentences(cands, seed=seed + rep_idx)

        # Assign 3 to FAITHFUL and 3 to CORRUPTED (seed-controlled)
        rng = random.Random(seed + rep_idx * 100)
        types = ["faithful"] * 3 + ["corrupted"] * 3
        rng.shuffle(types)

        # Format prompt block
        prompt_lines = []
        for i, ((p_idx, s_text), g_type) in enumerate(zip(selected_6, types), 1):
            tag = "FAITHFUL" if g_type == "faithful" else "CORRUPTED"
            prompt_lines.append(f"{i}. [{tag}] {s_text}")
        sentences_block = "\n".join(prompt_lines)

        print(f"[{rep_idx+1}/12] Generating claims for {report_id} ({topic[:40]}...)...")

        # Call LLM via invoke_with_retry
        if dry_run:
            # Mock claims for dry run
            gen_claims = {
                i: f"Paraphrase or corruption {i} for {selected_6[i-1][1][:30]}"
                for i in range(1, 7)
            }
        else:
            out = invoke_with_retry(
                chain,
                {"topic": topic, "sentences_block": sentences_block},
                max_attempts=3,
                model_label=model_name,
            )
            # Map structured items
            gen_claims = {item.id: item.text.strip() for item in out.claims}

        # Embed passages once for this report
        p_embs = embed(passages)

        # Process each of the 6 generated claims
        for i in range(1, 7):
            claim_idx = 100 + i  # 101, 102, ..., 106
            source_p_idx, source_sentence = selected_6[i - 1]
            gen_type = types[i - 1]
            claim_text = gen_claims.get(i, "").strip()

            if not claim_text:
                raise RuntimeError(f"Missing generated claim for item {i} in report {report_id}")

            # Evidence retrieval using MiniLM cosine similarity (same as collect_claims)
            c_emb = embed([claim_text])[0]
            sims = np.dot(p_embs, c_emb)
            top_k_indices = list(np.argsort(sims)[::-1][:min(2, len(passages))])

            if gen_type == "faithful":
                total_faithful += 1
                if source_p_idx in top_k_indices:
                    # Retrieval hit: top-2 as retrieved
                    ev1 = passages[top_k_indices[0]]
                    ev2 = passages[top_k_indices[1]] if len(top_k_indices) > 1 else ""
                else:
                    # Retrieval miss: guarantee source is shown in evidence_top1
                    faithful_retrieval_misses += 1
                    ev1 = passages[source_p_idx]
                    ev2 = passages[top_k_indices[0]] if len(top_k_indices) > 0 else ""
            else:
                total_corrupted += 1
                ev1 = passages[top_k_indices[0]] if len(top_k_indices) > 0 else ""
                ev2 = passages[top_k_indices[1]] if len(top_k_indices) > 1 else ""

            # Ensure clean single-line strings
            ev1_clean = re.sub(r"\s+", " ", ev1).strip()
            ev2_clean = re.sub(r"\s+", " ", ev2).strip()
            claim_clean = re.sub(r"\s+", " ", claim_text).strip()

            synthetic_rows.append({
                "report_id": report_id,
                "topic": topic,
                "claim_index": claim_idx,
                "claim": claim_clean,
                "evidence_top1": ev1_clean,
                "evidence_top2": ev2_clean,
                "label": "",  # Empty for blind human annotation
                "source": "synthetic",
            })

            key_rows.append({
                "report_id": report_id,
                "claim_index": claim_idx,
                "gen_type": gen_type,
                "source_sentence": source_sentence,
            })

    # 2. Build DataFrames
    df_synthetic = pd.DataFrame(synthetic_rows)
    df_key = pd.DataFrame(key_rows)

    assert len(df_synthetic) == 72, f"Expected 72 synthetic rows, got {len(df_synthetic)}"
    assert len(df_key) == 72, f"Expected 72 key rows, got {len(df_key)}"

    # 3. Shuffle synthetic rows across reports (seed 42)
    rng_shuffle = np.random.RandomState(seed)
    perm = rng_shuffle.permutation(len(df_synthetic))
    df_synthetic = df_synthetic.iloc[perm].reset_index(drop=True)

    # 4. Audit checks (assert, same style as collect_claims step 6)
    ev1_s = df_synthetic["evidence_top1"].astype(str)
    ev2_s = df_synthetic["evidence_top2"].astype(str)
    claim_s = df_synthetic["claim"].astype(str)

    t_cnt = int((ev1_s.str.contains("Title:") | ev2_s.str.contains("Title:") | claim_s.str.contains("Title:")).sum())
    u_cnt = int((ev1_s.str.contains("URL:") | ev2_s.str.contains("URL:") | claim_s.str.contains("URL:")).sum())
    nl_cnt = int((ev1_s.str.contains("\n") | ev2_s.str.contains("\n") | claim_s.str.contains("\n")).sum())
    ml_regex = r"\[.*?\]\(.*?\)"
    ml_cnt = int((ev1_s.str.contains(ml_regex) | ev2_s.str.contains(ml_regex) | claim_s.str.contains(ml_regex)).sum())

    print("\n--- Audit Verification ---")
    print(f"Rows with 'Title:':       {t_cnt}")
    print(f"Rows with 'URL:':         {u_cnt}")
    print(f"Rows with markdown links: {ml_cnt}")
    print(f"Rows with hard newlines:  {nl_cnt}")
    assert t_cnt == 0, f"Found {t_cnt} rows with 'Title:'"
    assert u_cnt == 0, f"Found {u_cnt} rows with 'URL:'"
    assert ml_cnt == 0, f"Found {ml_cnt} rows with markdown links"
    assert nl_cnt == 0, f"Found {nl_cnt} rows with hard newlines"

    # Verbatim check against source sentence
    key_map = {(r["report_id"], r["claim_index"]): r["source_sentence"] for _, r in df_key.iterrows()}
    for _, r in df_synthetic.iterrows():
        src_sent = key_map.get((r["report_id"], r["claim_index"]), "")
        assert r["claim"].strip() != src_sent.strip(), f"Claim verbatim to source sentence: {r['claim']}"

    # Duplicate claims check
    assert len(df_synthetic["claim"]) == len(df_synthetic["claim"].unique()), "Duplicate claims detected in synthetic set!"

    # Label leakage check: verify no column reveals faithful vs corrupted
    assert "gen_type" not in df_synthetic.columns
    assert set(df_synthetic.columns) == {
        "report_id", "topic", "claim_index", "claim", "evidence_top1", "evidence_top2", "label", "source"
    }

    # 5. Save output files
    df_synthetic.to_csv(SYNTHETIC_OUTPUT_PATH, index=False)
    df_key.to_csv(SYNTHETIC_KEY_PATH, index=False)

    miss_rate = (faithful_retrieval_misses / total_faithful) if total_faithful > 0 else 0.0

    print("\n=== GENERATION COMPLETE ===")
    print(f"Synthetic claims saved to: {SYNTHETIC_OUTPUT_PATH} ({len(df_synthetic)} rows)")
    print(f"Synthetic key saved to:    {SYNTHETIC_KEY_PATH} ({len(df_key)} rows)")
    print(f"Token usage: {TOKEN_USAGE}")
    print(f"Faithful claims: {total_faithful} | Corrupted claims: {total_corrupted}")
    print(f"Retrieval miss rate for FAITHFUL claims: {miss_rate:.2%} ({faithful_retrieval_misses}/{total_faithful})")

    return {
        "n_synthetic": len(df_synthetic),
        "token_usage": dict(TOKEN_USAGE),
        "faithful_miss_rate": miss_rate,
        "miss_count": faithful_retrieval_misses,
        "total_faithful": total_faithful,
        "total_corrupted": total_corrupted,
    }


def main():
    parser = argparse.ArgumentParser(description="Generate controlled claims")
    parser.add_argument("--seed", type=int, default=42, help="Random seed (default: 42)")
    parser.add_argument("--dry_run", action="store_true", help="Dry run without LLM calls")
    args = parser.parse_args()

    run_controlled_generation(seed=args.seed, dry_run=args.dry_run)


if __name__ == "__main__":
    main()
