"""Generate controlled synthetic claims for class-balanced faithfulness evaluation.

Generates 72 synthetic claims (6 per report across 12 diverse reports):
- 3 FAITHFUL paraphrases (expected label 1: supported)
- 3 CORRUPTED single-fact edits (expected label 0: unsupported)
Both are generated by the SAME LLM (GROQ_MODEL at temperature 0) using structured JSON output.
The human annotates them blind (label column left empty in validation_claims_synthetic.csv).
The true generator types are stored in synthetic_key.csv.
"""

